const dicts: Record<string, Dict> = { en, zh }
const lang = ref('en')

export function tLang(
  code: 'en' | 'zh',
  key: string,
  vars?: Record<string, string | number>,
) {
  return applyVars(dicts[code]?.[key] ?? dicts.en[key] ?? key, vars)
}

export function useI18n() {
  const translate = (key: string, vars?: Record<string, string | number>) =>
    applyVars(dicts[lang.value]?.[key] ?? dicts.en[key] ?? key, vars)
  return {
    lang: computed(() => lang.value),
    setLang: (l: string) => {
      lang.value = l in dicts ? l : 'en'
    },
    t: translate,
    tLang,
  }
}

export function setI18nLang(l: string) {
  lang.value = l in dicts ? l : 'en'
}

export function t(key: string, vars?: Record<string, string | number>) {
  return applyVars(dicts[lang.value]?.[key] ?? dicts.en[key] ?? key, vars)
}
