type Dict = Record<string, string>

function applyVars(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s
  let out = s
  for (const [k, v] of Object.entries(vars)) {
    out = out.split(`{${k}}`).join(String(v))
  }
  return out
}

